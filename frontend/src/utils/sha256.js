/*
  SHA-256 en JavaScript puro (el mismo algoritmo que usaba prueba.html).
  No se usa crypto.subtle porque solo existe en contextos seguros (https o localhost)
  y el cliente también debe funcionar al abrirlo por IP en la red local.
  El texto se codifica en UTF-8 antes de calcular el hash; para contraseñas ASCII
  el resultado es idéntico al de la versión original.
*/
export function sha256(texto) {
  const rightRotate = (value, amount) => (value >>> amount) | (value << (32 - amount));

  // Texto -> bytes UTF-8 representados como caracteres 0..255
  let ascii = "";
  for (const b of new TextEncoder().encode(texto)) ascii += String.fromCharCode(b);

  const maxWord = 2 ** 32;
  const asciiBitLength = ascii.length * 8;
  const words = [];
  let hash = [];
  const k = [];
  let primeCounter = 0;
  const isComposite = {};
  let i, j;

  for (let candidate = 2; primeCounter < 64; candidate++) {
    if (!isComposite[candidate]) {
      for (i = 0; i < 313; i += candidate) isComposite[i] = candidate;
      hash[primeCounter] = (Math.pow(candidate, 0.5) * maxWord) | 0;
      k[primeCounter++] = (Math.pow(candidate, 1 / 3) * maxWord) | 0;
    }
  }

  ascii += "\x80";
  while ((ascii.length % 64) - 56) ascii += "\x00";
  for (i = 0; i < ascii.length; i++) {
    j = ascii.charCodeAt(i);
    words[i >> 2] |= j << (((3 - i) % 4) * 8);
  }
  words[words.length] = (asciiBitLength / maxWord) | 0;
  words[words.length] = asciiBitLength;

  for (j = 0; j < words.length; ) {
    const w = words.slice(j, (j += 16));
    const oldHash = hash.slice(0);
    for (i = 0; i < 64; i++) {
      const w15 = w[i - 15];
      const w2 = w[i - 2];
      const a = hash[0];
      const e = hash[4];
      const temp1 =
        hash[7] +
        (rightRotate(e, 6) ^ rightRotate(e, 11) ^ rightRotate(e, 25)) +
        ((e & hash[5]) ^ (~e & hash[6])) +
        k[i] +
        (w[i] =
          i < 16
            ? w[i]
            : (w[i - 16] +
                (rightRotate(w15, 7) ^ rightRotate(w15, 18) ^ (w15 >>> 3)) +
                w[i - 7] +
                (rightRotate(w2, 17) ^ rightRotate(w2, 19) ^ (w2 >>> 10))) |
              0);
      const temp2 =
        (rightRotate(a, 2) ^ rightRotate(a, 13) ^ rightRotate(a, 22)) +
        ((a & hash[1]) ^ (a & hash[2]) ^ (hash[1] & hash[2]));
      hash = [(temp1 + temp2) | 0].concat(hash);
      hash[4] = (hash[4] + temp1) | 0;
      hash.pop();
    }
    for (i = 0; i < 8; i++) hash[i] = (hash[i] + oldHash[i]) | 0;
  }

  let resultado = "";
  for (i = 0; i < 8; i++) {
    for (j = 3; j + 1; j--) {
      const b = (hash[i] >> (j * 8)) & 255;
      resultado += (b < 16 ? "0" : "") + b.toString(16);
    }
  }
  return resultado;
}
